/**
 * Generate P&L HTML content
 */
export const generatePLReport = (data: {
  revenue: number;
  costOfGoods: number;
  grossProfit: number;
  transactionCount: number;
  avgOrderValue: number;
  dateRange: string;
  topProducts: Array<{ name: string; quantity: number; revenue: number }>;
  paymentBreakdown: Array<{ method: string; amount: number; count: number }>;
}) => {
  const grossMargin = data.revenue > 0 ? ((data.grossProfit / data.revenue) * 100).toFixed(1) : '0';

  return `
    <div class="summary-grid">
      <div class="summary-card"><div class="label">Total Revenue</div><div class="value">KES ${data.revenue.toLocaleString()}</div></div>
      <div class="summary-card"><div class="label">Cost of Goods</div><div class="value">KES ${data.costOfGoods.toLocaleString()}</div></div>
      <div class="summary-card"><div class="label">Gross Profit</div><div class="value">KES ${data.grossProfit.toLocaleString()}</div></div>
      <div class="summary-card"><div class="label">Gross Margin</div><div class="value">${grossMargin}%</div></div>
    </div>

    <div class="section-title">Profit & Loss Statement — ${data.dateRange}</div>
    <table>
      <tr><td><strong>Revenue</strong></td><td class="number"><strong>KES ${data.revenue.toLocaleString()}</strong></td></tr>
      <tr><td>Less: Cost of Goods Sold</td><td class="number">(KES ${data.costOfGoods.toLocaleString()})</td></tr>
      <tr class="total-row"><td><strong>Gross Profit</strong></td><td class="number"><strong>KES ${data.grossProfit.toLocaleString()}</strong></td></tr>
      <tr><td>Gross Margin</td><td class="number">${grossMargin}%</td></tr>
      <tr><td>Total Transactions</td><td class="number">${data.transactionCount}</td></tr>
      <tr><td>Average Order Value</td><td class="number">KES ${data.avgOrderValue.toLocaleString()}</td></tr>
    </table>

    <div class="section-title">Top Products by Revenue</div>
    <table>
      <thead><tr><th>#</th><th>Product</th><th class="number">Qty Sold</th><th class="number">Revenue</th></tr></thead>
      <tbody>
        ${data.topProducts.map((p, i) => `<tr><td>${i + 1}</td><td>${p.name}</td><td class="number">${p.quantity}</td><td class="number">KES ${p.revenue.toLocaleString()}</td></tr>`).join('')}
      </tbody>
    </table>

    <div class="section-title">Payment Breakdown</div>
    <table>
      <thead><tr><th>Method</th><th class="number">Count</th><th class="number">Amount</th></tr></thead>
      <tbody>
        ${data.paymentBreakdown.map(p => `<tr><td>${p.method}</td><td class="number">${p.count}</td><td class="number">KES ${p.amount.toLocaleString()}</td></tr>`).join('')}
      </tbody>
    </table>
  `;
};

// Helpers
function downloadFile(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  link.click();
  URL.revokeObjectURL(url);
}

function formatHeader(key: string): string {
  return key.replace(/_/g, ' ').replace(/\b\w/g, c => c.toUpperCase());
}
