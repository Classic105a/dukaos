import { format } from 'date-fns';

/**
 * Export data as CSV file download
 */
export const exportToCSV = (data: Record<string, any>[], filename: string) => {
  if (data.length === 0) return;

  const headers = Object.keys(data[0]);
  const csvContent = [
    headers.join(','),
    ...data.map(row =>
      headers.map(header => {
        const value = row[header];
        // Escape commas and quotes
        if (typeof value === 'string' && (value.includes(',') || value.includes('"') || value.includes('\n'))) {
          return `"${value.replace(/"/g, '""')}"`;
        }
        return value ?? '';
      }).join(',')
    ),
  ].join('\n');

  downloadFile(csvContent, `${filename}.csv`, 'text/csv;charset=utf-8;');
};

/**
 * Export data as Excel-compatible HTML table (opens in Excel)
 */
export const exportToExcel = (data: Record<string, any>[], filename: string, title?: string) => {
  if (data.length === 0) return;

  const headers = Object.keys(data[0]);
  const htmlContent = `
    <html xmlns:o="urn:schemas-microsoft-com:office:office" xmlns:x="urn:schemas-microsoft-com:office:excel">
    <head><meta charset="utf-8">
    <style>
      table { border-collapse: collapse; width: 100%; }
      th, td { border: 1px solid #ddd; padding: 8px; text-align: left; font-family: Arial, sans-serif; font-size: 12px; }
      th { background-color: #1e3a5f; color: white; font-weight: bold; }
      tr:nth-child(even) { background-color: #f9f9f9; }
      .title { font-size: 16px; font-weight: bold; margin-bottom: 8px; }
      .meta { font-size: 11px; color: #666; margin-bottom: 12px; }
      .number { text-align: right; }
    </style>
    </head>
    <body>
      ${title ? `<div class="title">${title}</div>` : ''}
      <div class="meta">Generated: ${format(new Date(), 'dd MMM yyyy HH:mm')}</div>
      <table>
        <thead><tr>${headers.map(h => `<th>${formatHeader(h)}</th>`).join('')}</tr></thead>
        <tbody>
          ${data.map(row => `<tr>${headers.map(h => {
            const val = row[h];
            const isNum = typeof val === 'number';
            return `<td class="${isNum ? 'number' : ''}">${val ?? ''}</td>`;
          }).join('')}</tr>`).join('')}
        </tbody>
      </table>
    </body></html>
  `;

  downloadFile(htmlContent, `${filename}.xls`, 'application/vnd.ms-excel;charset=utf-8;');
};

